/** Compass 0.5.77.37.1 · Remember previously entered reps and weight per exercise.
 * Read-only suggestions from the encrypted local strengthJournal; no browser storage,
 * remote requests, or changes to already saved training sessions.
 */
const valid = v => typeof v === 'number' && Number.isFinite(v) && v >= 0;
const dateMs = v => {const n=Date.parse(v||'');return Number.isFinite(n)?n:null;};

/** Last explicitly saved value for each field, from an earlier workout.
 * A later set with unknown weight does NOT erase the last known weight.
 * Never suggest a value from a future session or the current one.
 */
export function recentStrengthExerciseValues(state, exerciseId, {before=null, excludeSessionId=null}={}){
 if(!exerciseId)return null;
 const beforeMs=before?dateMs(before):null;
 const rows=[];
 for(const ann of state?.strengthJournal?.annotations||[]){
  if(!ann||!Array.isArray(ann.sets)||ann.sessionId===excludeSessionId)continue;
  const ms=dateMs(ann.start);
  if(ms===null||(beforeMs!==null&&beforeMs!==undefined&&ms>=beforeMs))continue;
  ann.sets.forEach((s,i)=>{if(s?.exerciseId===exerciseId)rows.push({ms,i,s});});
 }
 rows.sort((a,b)=>b.ms-a.ms||b.i-a.i);
 const latest={reps:null,weightKg:null,day:null};
 for(const r of rows){
  if(latest.reps===null&&valid(r.s.reps))latest.reps=r.s.reps;
  if(latest.weightKg===null&&valid(r.s.weightKg))latest.weightKg=r.s.weightKg;
  if(!latest.day&&(valid(r.s.reps)||valid(r.s.weightKg)))latest.day=new Date(r.ms).toISOString().slice(0,10);
  if(latest.reps!==null&&latest.weightKg!==null)break;
 }
 return latest.day?latest:null;
}

const readNumber=input=>{
 if(!input||String(input.value??'').trim()==='')return null;
 const v=Number(String(input.value).replace(',','.'));
 return valid(v)?v:null;
};

/** Event delegation means dynamically added sets get the same defaults automatically.
 * Never overwrite an existing value typed by the user, imported by Garmin, or saved
 * in an earlier edit. Switching the exercise removes ONLY unchanged auto-filled values.
 */
export function wireStrengthRecentDefaults(form,state){
 if(!form||!state||form.dataset.strengthRecentWired==='1')return;
 form.dataset.strengthRecentWired='1';
 const autogenerated=new WeakMap();
 const undoOwnAuto=(input)=>{
  if(!input)return;
  const previous=autogenerated.get(input);
  if(previous!==undefined&&input.value===previous)input.value='';
  autogenerated.delete(input);
 };
 const earlierSetValues=(row,id)=>{
  const rows=[...form.querySelectorAll('[data-strength-set]')];
  const rowIndex=rows.indexOf(row);
  const result={reps:null,weightKg:null};
  for(let i=rowIndex-1;i>=0;i--){
   const candidate=rows[i];
   if(candidate.querySelector('select[name^="exercise-"]')?.value!==id)continue;
   if(result.reps===null)result.reps=readNumber(candidate.querySelector('input[name^="reps-"]'));
   if(result.weightKg===null)result.weightKg=readNumber(candidate.querySelector('input[name^="weight-"]'));
   if(result.reps!==null&&result.weightKg!==null)break;
  }
  return result;
 };
 const hintFor=(row,history,id)=>{
  let hint=row.querySelector('.str7371-recent-hint');
  if(!hint){hint=document.createElement('small');hint.className='str7371-recent-hint';row.appendChild(hint);}
  if(!id||!history){hint.textContent='';hint.hidden=true;return;}
  const parts=[];
  if(history.weightKg!==null)parts.push(`${history.weightKg.toLocaleString('de-AT',{maximumFractionDigits:2})} kg`);
  if(history.reps!==null)parts.push(`${history.reps} Wdh.`);
  hint.textContent=parts.length?`Zuletzt erfasst: ${parts.join(' · ')} · Vorschlag, jederzeit änderbar`:'';
  hint.hidden=!parts.length;
 };
 form.addEventListener('change',event=>{
  const select=event.target;
  if(!select?.matches?.('select[name^="exercise-"]'))return;
  const row=select.closest('[data-strength-set]');if(!row)return;
  const reps=row.querySelector('input[name^="reps-"]');
  const weight=row.querySelector('input[name^="weight-"]');
  // Only undo values we ourselves inserted and the user has not edited.
  undoOwnAuto(reps);undoOwnAuto(weight);
  const id=select.value;
  if(!id){hintFor(row,null,id);return;}
  const history=recentStrengthExerciseValues(state,id,{before:form.dataset.start,excludeSessionId:form.dataset.sessionId});
  const within=earlierSetValues(row,id);
  const values={reps:within.reps??history?.reps??null,weightKg:within.weightKg??history?.weightKg??null};
  if(reps&&reps.value.trim()===''&&values.reps!==null){reps.value=String(values.reps);autogenerated.set(reps,reps.value);}
  if(weight&&weight.value.trim()===''&&values.weightKg!==null){weight.value=String(values.weightKg);autogenerated.set(weight,weight.value);}
  hintFor(row,history,id);
 });
}
