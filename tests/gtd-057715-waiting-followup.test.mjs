test('0.5.77.15 postpones and resolves existing followups, no reappearance after closing',()=>{
 const wf=makeWaitingFollowup(origin,{id:b,day:'2026-10-27',title:'Antwort prüfen'});
 const s={tasks:{[a]:origin,[b]:wf}};
 const postponed=postponeWaitingFollowup(wf,'2026-10-27',5);
 assert.equal(postponed.plannedDate,'2026-11-03');
 s.tasks[b]=postponed;
 assert.equal(waitingFollowupsDue(s,'2026-10-27').length,0);
 assert.equal(waitingFollowupsDue(s,'2026-11-03').length,1);
 s.tasks[b]={...postponed,completed:true};assert.equal(waitingFollowupsDue(s,'2026-11-04').length,0);
 assert.equal(currentFollowupFor(s,a),null);
});
